export const DEFAULT_NOTIFICATION_settings = {
  telegramEnabled: true,
  remind3Days: true,
  remind1Day: true,
  remindDue: true,
  remindOverdue: true,
  timezone: "Africa/Lagos",
  reminderHour: 8,
  reminderMinute: 0,
};

export async function getNotificationsettings(companyId) {
  const res = await db.execute({
    sql: `SELECT * FROM notification_settings WHERE company_id = ?`,
    args: [companyId],
  });

  const row = res.rows[0];

  if (!row) {
    return {
      companyId,
      ...DEFAULT_NOTIFICATION_settings,
    };
  }

  return {
    companyId,
    telegramEnabled: Boolean(row.telegram_enabled),
    remind3Days: Boolean(row.remind_3_days),
    remind1Day: Boolean(row.remind_1_day),
    remindDue: Boolean(row.remind_due),
    remindOverdue: Boolean(row.remind_overdue),
    timezone: row.timezone || "Africa/Lagos",
    reminderHour: Number(row.reminder_hour ?? 8),
    reminderMinute: Number(row.reminder_minute ?? 0),
  };
}

export async function saveNotificationsettings(companyId, settings = {}) {
  const current = await getNotificationsettings(companyId);

  const next = {
    ...current,
    ...settings,
  };

  await db.execute({
    sql: `
      INSERT INTO notification_settings (
        company_id,
        telegram_enabled,
        remind_3_days,
        remind_1_day,
        remind_due,
        remind_overdue,
        timezone,
        reminder_hour,
        reminder_minute,
        updated_at
      )
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
      ON CONFLICT(company_id) DO UPDATE SET
        telegram_enabled = excluded.telegram_enabled,
        remind_3_days = excluded.remind_3_days,
        remind_1_day = excluded.remind_1_day,
        remind_due = excluded.remind_due,
        remind_overdue = excluded.remind_overdue,
        timezone = excluded.timezone,
        reminder_hour = excluded.reminder_hour,
        reminder_minute = excluded.reminder_minute,
        updated_at = excluded.updated_at
    `,
    args: [
      companyId,
      next.telegramEnabled ? 1 : 0,
      next.remind3Days ? 1 : 0,
      next.remind1Day ? 1 : 0,
      next.remindDue ? 1 : 0,
      next.remindOverdue ? 1 : 0,
      next.timezone || "Africa/Lagos",
      Number(next.reminderHour ?? 8),
      Number(next.reminderMinute ?? 0),
      nowISO(),
    ],
  });

  return getNotificationsettings(companyId);
}

