import { createClient } from "@libsql/client";
import { randomUUID } from "crypto";
import dotenv from "dotenv";
dotenv.config();

export const db = createClient({
  url: process.env.TURSO_DATABASE_URL,
  authToken: process.env.TURSO_AUTH_TOKEN,
});

export const uid = () => randomUUID();
export const nowISO = () => new Date().toISOString();

// entities we relay, matching ENTITY_TABLE in useCompanySync.js
export const ENTITY_TYPES = ["product", "transaction", "settlement", "pendingOrder", "invoice", "deadline"];

const SCHEMA = [
  // Which Telegram chats are linked to which companyId. One company can
  // have several chats (e.g. owner + a staff member's chat).
  `CREATE TABLE IF NOT EXISTS chats (
    chat_id     INTEGER PRIMARY KEY,
    company_id  TEXT NOT NULL,
    linked_at   TEXT
  )`,
  `CREATE INDEX IF NOT EXISTS idx_chats_company ON chats(company_id)`,

  // Business profile — fetched from the real server's /api/sync/business,
  // cached here only for quick reads (source of truth is always the server).
  `CREATE TABLE IF NOT EXISTS business (
    id          TEXT PRIMARY KEY,
    data        TEXT NOT NULL,
    updated_at  TEXT
  )`,

  // One row per entity record, storing the record's data EXACTLY as it
  // travels over SYNC_MUTATE / SYNC_EVENT / STATE_OFFERED (camelCase
  // fields, nested arrays like product.entries preserved as-is). This is
  // what makes the bot a faithful peer instead of a lossy re-modeling.
  `CREATE TABLE IF NOT EXISTS entities (
    entity      TEXT NOT NULL,   -- 'product' | 'transaction' | 'settlement' | 'pendingOrder' | 'invoice'
    id          TEXT NOT NULL,
    company_id  TEXT NOT NULL,
    data        TEXT NOT NULL,   -- JSON, the full record as received
    updated_at  TEXT,
    deleted     INTEGER DEFAULT 0,
    PRIMARY KEY (entity, id)
  )`,
  `CREATE INDEX IF NOT EXISTS idx_entities_company ON entities(company_id, entity)`,

  // One-time pairing codes generated by the dashboard, consumed via /link.
  `CREATE TABLE IF NOT EXISTS pairing_codes (
    code        TEXT PRIMARY KEY,
    company_id  TEXT NOT NULL,
    channel     TEXT NOT NULL DEFAULT 'telegram',
    created_at  TEXT,
    expires_at  TEXT NOT NULL,
    used        INTEGER DEFAULT 0
  )`,

  `CREATE TABLE IF NOT EXISTS monthly_statements (
    id TEXT PRIMARY KEY,
    company_id TEXT NOT NULL,
    period_start TEXT NOT NULL,
    period_end TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'ready',
    generated_at TEXT NOT NULL,
    opening_balance REAL NOT NULL DEFAULT 0,
    total_sales REAL NOT NULL DEFAULT 0,
    total_purchases REAL NOT NULL DEFAULT 0,
    total_expenses REAL NOT NULL DEFAULT 0,
    total_debtors REAL NOT NULL DEFAULT 0,
    total_creditors REAL NOT NULL DEFAULT 0,
    net_profit REAL NOT NULL DEFAULT 0,
    payload TEXT NOT NULL,
    UNIQUE(company_id, period_start, period_end)
  )`,
  `CREATE INDEX IF NOT EXISTS idx_monthly_statements_company
     ON monthly_statements(company_id, period_end)`,

  `CREATE TABLE IF NOT EXISTS monthly_statement_deliveries (
    id TEXT PRIMARY KEY,
    statement_id TEXT NOT NULL,
    company_id TEXT NOT NULL,
    channel TEXT NOT NULL,
    recipient TEXT NOT NULL,
    sent_at TEXT,
    status TEXT NOT NULL,
    error TEXT,
    UNIQUE(statement_id, channel, recipient)
  )`,
  `CREATE INDEX IF NOT EXISTS idx_monthly_statement_deliveries_statement
     ON monthly_statement_deliveries(statement_id, channel)`,

  // Per-company notification and reminder preferences
  `CREATE TABLE IF NOT EXISTS notification_settings (
    company_id              TEXT PRIMARY KEY,
    telegram_enabled        INTEGER NOT NULL DEFAULT 1,
    remind_3_days           INTEGER NOT NULL DEFAULT 1,
    remind_1_day            INTEGER NOT NULL DEFAULT 1,
    remind_due              INTEGER NOT NULL DEFAULT 1,
    remind_overdue          INTEGER NOT NULL DEFAULT 1,
    timezone                TEXT NOT NULL DEFAULT 'Africa/Lagos',
    reminder_hour           INTEGER NOT NULL DEFAULT 8,
    reminder_minute         INTEGER NOT NULL DEFAULT 0,
    updated_at              TEXT
  )`,

  // Tracks reminder notification delivery status
  `CREATE TABLE IF NOT EXISTS notification_attempts (
    id             TEXT PRIMARY KEY,
    company_id     TEXT NOT NULL,
    deadline_id    TEXT NOT NULL,
    channel        TEXT NOT NULL,
    reminder_type  TEXT NOT NULL,
    scheduled_date TEXT NOT NULL,
    status         TEXT NOT NULL,
    error          TEXT,
    created_at     TEXT NOT NULL,
    UNIQUE(company_id, deadline_id, channel, reminder_type, scheduled_date)
  )`,

  // Bot-originated mutations waiting to be delivered to the sync mesh
  // (cache mode only — mirrors the app's own `outbox` table in Db.js).
  `CREATE TABLE IF NOT EXISTS bot_outbox (
    local_id    INTEGER PRIMARY KEY AUTOINCREMENT,
    company_id  TEXT NOT NULL,
    entity      TEXT NOT NULL,
    action      TEXT NOT NULL,
    entity_id   TEXT,
    payload     TEXT,
    created_at  TEXT
  )`,

  `CREATE TABLE IF NOT EXISTS meta (
    key   TEXT PRIMARY KEY,
    value TEXT
  )`,

  // At most one "your device hasn't synced in a while" nudge per device
  // per calendar day — this is the dedup, same idea as
  // notification_attempts' (company_id, deadline_id, ...) uniqueness but
  // for device staleness instead of deadlines.
  `CREATE TABLE IF NOT EXISTS stale_device_notifications (
    company_id   TEXT NOT NULL,
    device_id    TEXT NOT NULL,
    notified_on  TEXT NOT NULL, -- YYYY-MM-DD
    created_at   TEXT NOT NULL,
    PRIMARY KEY (company_id, device_id, notified_on)
  )`,

  // The business's own Evolution API (WhatsApp/Baileys) instance — one per
  // company. Tracks the instance Evolution created for us and its last
  // known connection state, so the bot doesn't re-create an instance on
  // every request.
  `CREATE TABLE IF NOT EXISTS evolution_instances (
    company_id      TEXT PRIMARY KEY,
    instance_name   TEXT NOT NULL,
    instance_token  TEXT,
    status          TEXT NOT NULL DEFAULT 'created',
    connected_at    TEXT,
    created_at      TEXT NOT NULL,
    updated_at      TEXT NOT NULL
  )`,

  // Customer WhatsApp numbers a company has saved (for sending invoices /
  // reports to). Distinct from evolution_instances, which is the
  // business's own sending connection.
  `CREATE TABLE IF NOT EXISTS whatsapp_clients (
    company_id   TEXT NOT NULL,
    wa_id        TEXT NOT NULL,
    name         TEXT,
    linked_at    TEXT NOT NULL,
    PRIMARY KEY (company_id, wa_id)
  )`,
  `CREATE INDEX IF NOT EXISTS idx_whatsapp_clients_company ON whatsapp_clients(company_id)`,
];

export async function initSchema() {
  for (const sql of SCHEMA) await db.execute(sql);
  // Migration for databases created before `channel` existed on
  // pairing_codes — CREATE TABLE IF NOT EXISTS won't add it retroactively.
  try {
    await db.execute(`ALTER TABLE pairing_codes ADD COLUMN channel TEXT NOT NULL DEFAULT 'telegram'`);
  } catch {
    // column already exists — fine
  }

  // Best-effort cleanup for databases created before WhatsApp support was
  // removed. DROP COLUMN requires a modern SQLite/libSQL; on an older one
  // this just no-ops via the catch, leaving the orphaned column in place
  // harmlessly (nothing reads it anymore).
  try {
    await db.execute(`ALTER TABLE notification_settings DROP COLUMN whatsapp_enabled`);
  } catch {
    // already dropped, or DROP COLUMN unsupported — fine either way
  }
  try {
    await db.execute(`ALTER TABLE notification_settings DROP COLUMN notification_wa_number`);
  } catch {
    // already dropped, or DROP COLUMN unsupported — fine either way
  }
}

