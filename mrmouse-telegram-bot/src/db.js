// ---------- entities (products, transactions, settlements, pendingOrders, invoices, deadlines) ----------
export async function upsertEntity(companyId, entity, record) {
  if (!record || !record.id) return;
  await db.execute({
    sql: `INSERT INTO entities (entity, id, company_id, data, updated_at, deleted)
          VALUES (?, ?, ?, ?, ?, ?)
          ON CONFLICT(entity, id) DO UPDATE SET
            data=excluded.data, updated_at=excluded.updated_at, deleted=excluded.deleted`,
    args: [entity, record.id, companyId, JSON.stringify(record), record.updatedAt || nowISO(), record.deleted ? 1 : 0],
  });
}

export async function softDeleteEntity(companyId, entity, id) {
  const existing = await getEntity(companyId, entity, id);
  if (!existing) return;
  await upsertEntity(companyId, entity, { ...existing, deleted: true, updatedAt: nowISO() });
}

// upsertEntity never actually removes a row — a soft-deleted record just
// sits in `entities` forever with deleted=1, since that's needed so a
// peer catching up after the fact still learns "this was deleted," not
// just "this doesn't exist." Over months of a long-lived bot process,
// that accumulates real space. Once a tombstone has been sitting for a
// month, it's had ample time to reach every device via the mesh and the
// durable backend replay — safe to actually remove it. Live (non-deleted)
// records are never touched here regardless of age; only tombstones age
// out.
export async function pruneOldTombstones(retentionDays = 30) {
  const cutoff = new Date(Date.now() - retentionDays * 24 * 60 * 60 * 1000).toISOString();
  const res = await db.execute({
    sql: `DELETE FROM entities WHERE deleted = 1 AND updated_at < ?`,
    args: [cutoff],
  });
  return res.rowsAffected || 0;
}

const TOMBSTONE_CLEANUP_INTERVAL_MS = 24 * 60 * 60 * 1000; // once a day is plenty for a month-long retention window

export function startTombstoneCleanupWorker(retentionDays = 30) {
  const run = () => {
    pruneOldTombstones(retentionDays)
      .then((count) => {
        if (count > 0) console.log(`[entities] pruned ${count} tombstone(s) older than ${retentionDays}d`);
      })
      .catch((err) => console.error("[entities] tombstone cleanup failed", err));
  };

  run();
  const timer = setInterval(run, TOMBSTONE_CLEANUP_INTERVAL_MS);
  timer.unref?.();

  console.log(`[entities] tombstone cleanup worker started; retention=${retentionDays}d`);
}

export async function getEntity(companyId, entity, id) {
  const res = await db.execute({
    sql: `SELECT data FROM entities WHERE entity = ? AND id = ? AND company_id = ?`,
    args: [entity, id, companyId],
  });
  return res.rows[0] ? JSON.parse(res.rows[0].data) : null;
}

export async function findEntityByField(companyId, entity, field, value) {
  const res = await db.execute({
    sql: `SELECT data FROM entities WHERE entity = ? AND company_id = ? AND deleted = 0`,
    args: [entity, companyId],
  });
  for (const row of res.rows) {
    const record = JSON.parse(row.data);
    if (typeof record[field] === "string" && record[field].toLowerCase() === String(value).toLowerCase()) {
      return record;
    }
  }
  return null;
}

export async function listEntities(companyId, entity, { includeDeleted = false } = {}) {
  const res = await db.execute({
    sql: includeDeleted
      ? `SELECT data FROM entities WHERE entity = ? AND company_id = ?`
      : `SELECT data FROM entities WHERE entity = ? AND company_id = ? AND deleted = 0`,
    args: [entity, companyId],
  });
  return res.rows.map((r) => JSON.parse(r.data));
}

// Snapshot of everything updated since a given ISO timestamp, in the same
// shape the app's own buildLocalSnapshot()/PROVIDE_STATE payload uses —
// so the bot can serve STATE_REQUESTED for real devices catching up.
export async function buildSnapshotSince(companyId, since) {
  const sinceDate = since ? new Date(since) : new Date(0);
  const out = {};
  for (const entity of ENTITY_TYPES) {
    const table = entity === "pendingOrder" ? "pendingOrders" : entity === "deadline" ? "deadlines" : `${entity}s`;
    const all = await listEntities(companyId, entity, { includeDeleted: true });
    out[table] = all.filter((r) => new Date(r.updatedAt || 0) > sinceDate);
  }
  return out;
}

// ---------- pairing codes ----------
export async function createPairingCode(companyId, channel = "telegram", ttlMinutes = 10) {
  const code = String(Math.floor(100000 + Math.random() * 900000)); // 6 digits
  const expiresAt = new Date(Date.now() + ttlMinutes * 60_000).toISOString();
  await db.execute({
    sql: `INSERT INTO pairing_codes (code, company_id, channel, created_at, expires_at, used) VALUES (?, ?, ?, ?, ?, 0)`,
    args: [code, companyId, channel, nowISO(), expiresAt],
  });
  return { code, expiresAt };
}

export async function consumePairingCode(code, channel = "telegram") {
  const res = await db.execute({ sql: `SELECT * FROM pairing_codes WHERE code = ?`, args: [code] });
  const row = res.rows[0];
  if (!row) return { ok: false, reason: "not_found" };
  if (row.channel !== channel) return { ok: false, reason: "not_found" }; // don't leak that it exists for another channel
  if (row.used) return { ok: false, reason: "used" };
  if (new Date(row.expires_at) < new Date()) return { ok: false, reason: "expired" };
  await db.execute({ sql: `UPDATE pairing_codes SET used = 1 WHERE code = ?`, args: [code] });
  return { ok: true, companyId: row.company_id };
}

