export async function linkWhatsApp(waId, companyId, name = null) {
  const now = nowISO();
  await db.execute({
    sql: `INSERT INTO whatsapp_clients (company_id, wa_id, name, linked_at)
          VALUES (?, ?, ?, ?)
          ON CONFLICT(company_id, wa_id) DO UPDATE SET
            name=excluded.name, linked_at=excluded.linked_at`,
    args: [companyId, waId, name, now],
  });
  const res = await db.execute({
    sql: `SELECT * FROM whatsapp_clients WHERE company_id = ? AND wa_id = ?`,
    args: [companyId, waId],
  });
  return res.rows[0] || null;
}

export async function unlinkWhatsApp(companyId, waId) {
  await db.execute({
    sql: `DELETE FROM whatsapp_clients WHERE company_id = ? AND wa_id = ?`,
    args: [companyId, waId],
  });
}

export async function listWhatsAppLinksForCompany(companyId) {
  const res = await db.execute({
    sql: `SELECT * FROM whatsapp_clients WHERE company_id = ? ORDER BY linked_at ASC`,
    args: [companyId],
  });
  return res.rows;
}